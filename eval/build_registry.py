def parse_skill_md(skill_dir):
    """解析 SKILL.md frontmatter，提取 name / display_name / description / domain。"""
    skill_md = os.path.join(skill_dir, 'SKILL.md')
    if not os.path.exists(skill_md):
        return None
    content = Path(skill_md).read_text(encoding='utf-8', errors='ignore')

    # 解析 YAML frontmatter
    meta = {}
    fm_match = re.match(r'^---\s*\n(.*?)\n---', content, re.DOTALL)
    if fm_match:
        fm = fm_match.group(1)
        for line in fm.split('\n'):
            m = re.match(r'^(\w+):\s*(.*)', line)
            if m:
                key, val = m.group(1), m.group(2).strip()
                # 去掉引号
                if val.startswith('"') and val.endswith('"'):
                    val = val[1:-1]
                elif val.startswith("'") and val.endswith("'"):
                    val = val[1:-1]
                meta[key] = val

    # 如果没有 name，用目录名
    dir_name = os.path.basename(skill_dir)
    name = meta.get('name', dir_name)

    # display_name: 优先用 frontmatter 的，否则用 name
    display_name = meta.get('display_name', meta.get('title', name))

    # description: 从 frontmatter 或第一段非 frontmatter 文本
    description = meta.get('description', '')
    if not description:
        # 去掉 frontmatter，取第一段非空文本
        body = re.sub(r'^---\s*\n.*?\n---\s*\n', '', content, flags=re.DOTALL)
        lines = [ln.strip() for ln in body.split('\n') if ln.strip() and not ln.startswith('#')]
        if lines:
            description = lines[0][:200]

    # domain: 从 frontmatter 或根据目录名推断
    domain = meta.get('domain', _infer_domain(name, description))

    # user_created: 从 frontmatter 或根据名称推断
    user_created = meta.get('user_created', 'false').lower() == 'true'
    source = meta.get('source', 'user-created' if user_created else 'community')

    return {
        'name': name,
        'display_name': display_name,
        'domain': domain,
        # 2026-09-22 第 10 轮：在役端实为 WB/TR/CX/HM（OC 已于 2026-09-21 退役、TC 是 TR 别名）
        # 2026-09-22 ZC（ZCode）入役：在役端扩为五端 = WB/TR/CX/HM/ZC
        # 2026-09-23 OC（OpenCode）入役：代号 oc 复用，在役端扩为六端 = WB/TR/CX/HM/ZC/OC
        # 2026-09-24 QW（千问办公，代号qw复用）/QD（Qoder CN）入役：在役端扩为八端
        # 2026-09-26 QW 退役（用户裁定 B 档）：在役端收敛为七端 = WB/TR/CX/HM/ZC/OC/QD
        #                       （顺序须与 truth_constants.endpoints.active 一致，test_r209 动态对账）
        'compatible_platforms': ['wb', 'tr', 'cx', 'hm', 'zc', 'oc', 'qd'],
        'user_created': user_created,
        'source': source,
        'install_state': dict(DEFAULT_INSTALL_STATE),
        'version': meta.get('version', 'community'),
        'description': description,
    }


def _infer_domain(name, description):
    """根据 skill 名称和描述推断域分类（权威 13 域，R194 迁移）。

    委托 domain_classifier（单一真相源），无匹配 → general_utils。
    旧数字前缀域（07-creative-writing 等）已退役，禁止再生成。
    """
    from domain_classifier import classify_domain
    cd = classify_domain(f"{name} {description or ''}")
    return cd if cd else 'general_utils'


_RETIRED_SKIPPED = []  # 2026-09-21：退役黑名单命中的磁盘 skill（按 R198.6 有意排除）


def scan_disk_skills():
    """扫描 global_skills + OC 插件目录，返回所有 skill 目录路径。"""
    try:
        from truth_constants import RETIRED_SKILLS
    except Exception:
        RETIRED_SKILLS = set()
    skills = {}
    # global_skills
    if os.path.isdir(GLOBAL_SKILLS):
        for d in os.listdir(GLOBAL_SKILLS):
            full = os.path.join(GLOBAL_SKILLS, d)
            if os.path.isdir(full) and d not in SYSTEM_DIRS:
                if d in RETIRED_SKILLS:
                    _RETIRED_SKIPPED.append(d)  # R198.6 退役黑名单：禁止批量入库还原
                    continue
                if os.path.exists(os.path.join(full, 'SKILL.md')):
                    skills[d] = full
    # OC 插件目录
    if os.path.isdir(PLUGIN_ROOT):
        for d in os.listdir(PLUGIN_ROOT):
            full = os.path.join(PLUGIN_ROOT, d)
            if os.path.isdir(full) and os.path.exists(os.path.join(full, 'SKILL.md')):
                if d in RETIRED_SKILLS:
                    _RETIRED_SKIPPED.append(d)  # R198.6 退役黑名单
                    continue
                if d not in skills:
                    skills[d] = full
    return skills


from io_utils import load_json  # P1-5: 读写原语唯一实现


def save_json(path, data):
    # 原子写（tmp + os.replace，与 build_indexes.write_json_atomic 同范式）：
    # 单一真相源注册表禁止半截 JSON —— 进程中断时磁盘保留旧完整版
    tmp = Path(path + '.tmp')
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    os.replace(tmp, path)


def reconcile_retired(uni_path):
    """R198.6 治本（2026-09-21）：注册表口径回收，清除退役 skill 的三处残留。

    历史缺陷（本次实测）：本脚本只增不删，且 `if not missing: return 0` 提前退出，
    导致退役条目永久留在清单里 —— cross_platform_map 9 条、platform-*.json 各 28-29 条，
    污染 eval/functional_dim_checks.py 的 route_cover 分母（health 98.3% ≠ 100 → guardrail G2 FAIL）。

    回收范围（口径 = 注册表集 ∩ 磁盘扫描集，退役黑名单已由 scan_disk_skills 排除）：
      ① unified-skills-index.json.skills
      ② cross_platform_map.json.skills + user_created_skills
      ③ platform-*.json.skills_list + user_created_skills + counts
    返回受影响的文件数（0 = 本就干净）。
    """
    disk = scan_disk_skills()
    valid = set(disk)                      # 磁盘真实在役（已排退役黑名单）
    changed = 0

    # 🛡️ fail-closed 空写保护（2026-09-21 R9 事故教训）：
    # 磁盘异常为空/骤降时（junction 被误删、盘未挂载、扫描失败），本函数会把注册表"回收"成空
    # —— 实测该场景已导致 <SKILLS_ROOT> 与 <MEMORY_ROOT> 被清空后的二次伤害。
    # 规则：磁盘集为空、或不足注册表规模的 50% 时，拒绝回收并报错退出。
    reg_n = len(load_json(uni_path).get('skills', {}))
    if reg_n and (len(valid) == 0 or len(valid) * 2 < reg_n):
        print(f'[3.5] 🛑 拒绝回收：磁盘在役 {len(valid)} << 注册表 {reg_n}'
              f'（疑似 junction 断裂/盘未挂载/扫描异常）→ 请先人工核查，勿盲目回收')
        return 0

    uni = load_json(uni_path)
    dead_uni = [n for n in uni.get('skills', {}) if n not in valid]
    if dead_uni:
        for n in dead_uni:
            del uni['skills'][n]
        save_json(uni_path, uni)
        changed += 1
        print(f'[3.5] unified-skills-index 回收 {len(dead_uni)} 条: {sorted(dead_uni)[:8]}')

    cpm_path = os.path.join(REGISTRY_DIR, 'cross_platform_map.json')
    if os.path.exists(cpm_path):
        cpm = load_json(cpm_path)
        cpm_skills = cpm.get('skills', {})
        dead = [n for n in cpm_skills if n not in valid]
        uc = cpm.get('user_created_skills')
        dead_uc = [n for n in uc if n not in valid] if isinstance(uc, list) else []
        if dead or dead_uc:
            for n in dead:
                del cpm_skills[n]
            if isinstance(uc, list):
                cpm['user_created_skills'] = [n for n in uc if n in valid]
            save_json(cpm_path, cpm)
            changed += 1
            print(f'[3.5] cross_platform_map 回收 {len(dead)} 条（+user_created {len(dead_uc)}）')

    for fname in ('platform-wb.json', 'platform-tc.json', 'platform-codex.json', 'platform-hm.json'):
        p = os.path.join(REGISTRY_DIR, fname)
        if not os.path.exists(p):
            continue
        pd = load_json(p)
        sl = pd.get('skills_list', [])
        dead = [n for n in sl if n not in valid]
        if not dead:
            continue
        pd['skills_list'] = sorted(n for n in sl if n in valid)
        if isinstance(pd.get('user_created_skills'), list):
            pd['user_created_skills'] = sorted(n for n in pd['user_created_skills'] if n in valid)
        pd['skills_count'] = len(pd['skills_list'])
        pd['user_created_count'] = len(pd['user_created_skills'])
        save_json(p, pd)
        changed += 1
        print(f'[3.5] {fname} 回收 {len(dead)} 条 → 剩 {pd["skills_count"]}')
    return changed


def add_meta_only():
    """为全部 registry JSON 写入 _meta 禁改标记（幂等，不触碰其他字段）。"""
    files = [
        'unified-skills-index.json', 'cross_platform_map.json', 'platform_tiers.json',
        'platform-wb.json', 'platform-tc.json', 'platform-codex.json',
        'platform-oc.json',
    ]
    for fname in files:
        path = os.path.join(REGISTRY_DIR, fname)
        if not os.path.exists(path):
            print(f'    ⚠ {fname} 不存在，跳过')
            continue
        data = load_json(path)
        data['_meta'] = AUTO_META
        save_json(path, data)
        print(f'    {fname}: _meta 已写')
    print('[DONE] registry _meta 禁改标记完成')


def rebuild(dry_run=False):
    """主重建逻辑。"""
    print('=' * 60)
    print('build_registry.py — 注册表重建')
    print('=' * 60)

    # 1. 扫描磁盘
    disk_skills = scan_disk_skills()
    _retired_hits = sorted(set(_RETIRED_SKIPPED))
    _retired_note = (f'（其中退役黑名单 {len(_retired_hits)} 个已按 R198.6 排除，非漏注册）'
                     if _retired_hits else '')
    print(f'[1] 磁盘扫描: {len(disk_skills)} skills{_retired_note}')
    if _retired_hits:
        print(f'    已排除退役: {_retired_hits}')

    # 2. 加载现有注册表
    uni_path = os.path.join(REGISTRY_DIR, 'unified-skills-index.json')
    uni = load_json(uni_path)
    reg_skills = uni.get('skills', {})
    print(f'[2] 现有注册表: {len(reg_skills)} skills')

    # 3. 找出缺失 skill
    missing = set(disk_skills) - set(reg_skills)
    extra = set(reg_skills) - set(disk_skills)
    print(f'[3] 磁盘有/注册表无: {len(missing)} skills → {sorted(missing)}')
    if _retired_hits:
        print('    ℹ️ 注：上述缺口已不含退役 skill；退役项（磁盘仍在/按设计不入库）不计入，'
              f'本次排除 {len(_retired_hits)} 个')
    if extra:
        print(f'    注册表有/磁盘无: {len(extra)} skills → {sorted(extra)}')

    # 3.5 口径回收（无条件执行，不受"无需补充"早退影响 —— R198.6 治本）
    reconcile_retired(uni_path)
    # 回收后重载，避免后续步骤用旧内存快照把残留写回
    uni = load_json(uni_path)
    reg_skills = uni.get('skills', {})

    if not missing:
        print('[4] 无需补充，注册表已完整')
        return 0

    # 4. 解析缺失 skill 的 SKILL.md 并添加到注册表
    added = 0
    for name in sorted(missing):
        skill_dir = disk_skills[name]
        meta = parse_skill_md(skill_dir)
        if meta is None:
            print(f'    ⚠ {name}: SKILL.md 解析失败，跳过')
            continue
        # 移除 description（注册表不存这个字段，只用于域推断）
        meta.pop('description', None)
        reg_skills[name] = meta
        added += 1
        print(f'    + {name} → domain={meta["domain"]}, user_created={meta["user_created"]}')

    print(f'[4] 补齐 {added} skills 到 unified-skills-index.json')

    # 5. 更新 cross_platform_map.json
    cpm_path = os.path.join(REGISTRY_DIR, 'cross_platform_map.json')
    cpm = load_json(cpm_path)
    cpm_skills = cpm.get('skills', {})
    cpm_added = 0
    for name in sorted(missing):
        if name not in cpm_skills:
            meta = reg_skills[name]
            cpm_skills[name] = {
                'install_state': meta['install_state'],
                'user_created': meta['user_created'],
                'source': meta['source'],
            }
            cpm_added += 1
    cpm['skills'] = cpm_skills
    # 版本号 +1
    old_ver = cpm.get('version', '1.0')
    ver_parts = old_ver.split('.')
    ver_parts[-1] = str(int(ver_parts[-1]) + 1)
    cpm['version'] = '.'.join(ver_parts)
    cpm['last_updated'] = datetime.datetime.now().isoformat(timespec='seconds')
    print(f'[5] 补齐 {cpm_added} skills 到 cross_platform_map.json (V{cpm["version"]})')

    # 6. 更新 unified-skills-index.json 元数据
    uni['skills'] = reg_skills
    uni['last_updated'] = datetime.datetime.now().isoformat(timespec='seconds')
    old_uni_ver = uni.get('version', '1.0')
    uni_ver_parts = old_uni_ver.split('.')
    uni_ver_parts[-1] = str(int(uni_ver_parts[-1]) + 1)
    uni['version'] = '.'.join(uni_ver_parts)
    print(f'[6] unified-skills-index.json 版本 → V{uni["version"]}')

    # 7. 更新 platform-*.json（为每个活跃端添加新 skill）
    # cc 已于 2026-09-08 弃用，其 platform-cc.json 不得存在于 registry（C4 要求废弃端无残留）。
    # oc 于 2026-09-21 随 OpenClaw 退役曾移出 registry，2026-09-23 代号由 OpenCode 接管复用，
    # platform-oc.json 已按 OpenCode 口径重建（见 _temp/gen_platform_oc.py），此后随活跃端正常更新。
    platform_files = {
        'wb': 'platform-wb.json',
        'tc': 'platform-tc.json',
        'cx': 'platform-codex.json',
        'oc': 'platform-oc.json',
        'hm': 'platform-hm.json',
    }
    for plat, fname in platform_files.items():
        fpath = os.path.join(REGISTRY_DIR, fname)
        if not os.path.exists(fpath):
            print(f'    ⚠ {fname} 不存在，跳过')
            continue
        pdata = load_json(fpath)
        skills_list = set(pdata.get('skills_list', []))
        uc_list = set(pdata.get('user_created_skills', []))
        added_here = 0
        for name in sorted(missing):
            meta = reg_skills[name]
            st = meta.get('install_state', {})
            # 判断该平台是否安装
            plat_key = 'codex' if plat == 'cx' else plat
            if st.get(plat_key) or st.get(plat):
                if name not in skills_list:
                    skills_list.add(name)
                    added_here += 1
                if meta.get('user_created') and name not in uc_list:
                    uc_list.add(name)
        pdata['skills_list'] = sorted(skills_list)
        pdata['user_created_skills'] = sorted(uc_list)
        pdata['skills_count'] = len(skills_list)
        pdata['user_created_count'] = len(uc_list)
        pdata['last_updated'] = datetime.datetime.now().isoformat(timespec='seconds')
        if not dry_run:
            save_json(fpath, pdata)
        print(f'    {fname}: +{added_here} skills (total={pdata["skills_count"]})')

    # 8. 写文件
    if dry_run:
        print('\n[DRY-RUN] 未写入任何文件')
    else:
        save_json(uni_path, uni)
        save_json(cpm_path, cpm)
        print(f'\n[DONE] 已写入 {len(reg_skills)} skills 到注册表')

    print('=' * 60)
    return 0


def _fm_explicit_keys(skill_dir):
    """返回 SKILL.md frontmatter 中**显式出现**的键集合。

    用于区分「frontmatter 显式声明」与「缺省推断」——refresh_fields 只覆盖前者。
    """
    p = os.path.join(skill_dir, 'SKILL.md')
    if not os.path.exists(p):
        return set()
    content = Path(p).read_text(encoding='utf-8', errors='ignore')
    m = re.match(r'^---\s*\n(.*?)\n---', content, re.DOTALL)
    if not m:
        return set()
    keys = set()
    for ln in m.group(1).split('\n'):
        mm = re.match(r'^([A-Za-z_][\w\-]*):', ln)
        if mm:
            keys.add(mm.group(1))
    return keys


def refresh_fields(dry_run=False):
    """按磁盘 SKILL.md frontmatter 刷新**已有**注册表条目的安全字段（2026-09-22 第 10 轮补）。

    动机（实测）：rebuild() 只对「磁盘有 / 注册表无」的 missing 集合做 parse+add（L263-295），
    **没有「已有条目字段刷新」路径** ⇒ 存量条目一旦过时（如 testing 缺 source、
    ican-frontend-design-system 缺 install_state/version）只能靠一次性人工脚本归一化。

    安全边界（宁漏不误伤）—— 只刷新「真相源明确在 frontmatter」的字段：
      · version      —— frontmatter 有 `version:` 才覆盖
      · source       —— frontmatter **显式**声明 `source:` 才覆盖（缺省不推断，
                        防把「自建但未标注」的件误降为 community）
      · user_created —— frontmatter **显式**声明 `user_created:` 才覆盖
      · compatible_platforms —— 仅在条目缺失该字段时按 DEFAULT 补齐
    **不动** domain / install_state / display_name / name（各有独立权威或含人工判断）。
    """
    reg_path = os.path.join(REGISTRY_DIR, 'unified-skills-index.json')
    uni = load_json(reg_path)
    reg_skills = uni.get('skills', {})
    disk = scan_disk_skills()
    changed = []
    for name, entry in sorted(reg_skills.items()):
        if name not in disk or not isinstance(entry, dict):
            continue
        d = disk[name]
        meta = parse_skill_md(d)
        if meta is None:
            continue
        explicit = _fm_explicit_keys(d)
        for fld in ('version', 'source', 'user_created'):
            if fld in explicit and entry.get(fld) != meta.get(fld):
                changed.append((name, fld, entry.get(fld), meta.get(fld)))
                if not dry_run:
                    entry[fld] = meta.get(fld)
        if 'compatible_platforms' not in entry:
            changed.append((name, 'compatible_platforms', None, meta.get('compatible_platforms')))
            if not dry_run:
                entry['compatible_platforms'] = meta.get('compatible_platforms')
    for name, fld, old, new in changed:
        print(f'    ~ {name}.{fld}: {old!r} -> {new!r}')
    print(f'[refresh] 变更 {len(changed)} 处' + ('（dry-run 未写盘）' if dry_run else ''))
    if changed and not dry_run:
        uni['skills'] = reg_skills
        save_json(reg_path, uni)
        print('[refresh] 已写盘 unified-skills-index.json')
    return 0


if __name__ == '__main__':
    if '--add-meta' in sys.argv:
        add_meta_only()
        sys.exit(0)
    if '--refresh' in sys.argv:
        sys.exit(refresh_fields('--dry-run' in sys.argv))
    dry_run = '--dry-run' in sys.argv
    sys.exit(rebuild(dry_run))
